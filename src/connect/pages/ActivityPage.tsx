import { useState } from "react";
import { useSim } from "../../teresa/hooks";
import { useConnect } from "../context";
import { ActivityTimeline } from "../components/ActivityTimeline";

export default function ActivityPage() {
  const { unitId } = useConnect();
  const { ward } = useSim();
  const [scope, setScope] = useState<"unit" | "all">("unit");
  const entries = scope === "unit" ? ward.log.filter((l) => l.unitId === unitId) : ward.log;
  return (
    <div className="page">
      <section className="card panel" aria-labelledby="act-title">
        <div className="panel__head">
          <h2 id="act-title">Activity log</h2>
          <div className="segmented" role="group" aria-label="Log scope">
            <button type="button" aria-pressed={scope === "unit"} onClick={() => setScope("unit")}>
              {ward.units[unitId].label}
            </button>
            <button type="button" aria-pressed={scope === "all"} onClick={() => setScope("all")}>
              All units
            </button>
          </div>
        </div>
        <p className="small muted">Newest first. Times are simulation time. Events are generated by the simulation state machine.</p>
        <ActivityTimeline entries={entries.slice(0, 200)} showUnit={scope === "all"} />
      </section>
    </div>
  );
}
